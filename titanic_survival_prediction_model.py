"""## **Hyperparameter Optimization with GridSearchCV**

To further improve the performance of the Decision Tree model, I used `GridSearchCV` to systematically search for the best combination of hyperparameters.
"""

from sklearn.model_selection import GridSearchCV
from sklearn.tree import DecisionTreeClassifier

# Define the parameter grid to search
param_grid = {
    'max_depth': [3, 4, 5, 6, 7, 8, None], # None means no limit
    'min_samples_split': [2, 5, 10, 15],
    'min_samples_leaf': [1, 2, 4, 6],
    'criterion': ['gini', 'entropy'] # Splitting criterion
}

# Initialize GridSearchCV
# We'll use the 'dt_pruned' model as a base for optimization
grid_search_dt = GridSearchCV(
    estimator=DecisionTreeClassifier(random_state=42),
    param_grid=param_grid,
    cv=5, # 5-fold cross-validation
    scoring='accuracy', # Metric to optimize
    n_jobs=-1, # Use all available CPU cores
    verbose=1
)

# Fit GridSearchCV to the training data
grid_search_dt.fit(X_train, y_train)

print("Best parameters found: ", grid_search_dt.best_params_)
print("Best cross-validation accuracy: ", round(grid_search_dt.best_score_, 4))

# Get the best estimator (the optimized model)
best_dt_model = grid_search_dt.best_estimator_

# Evaluate the optimized model on the test set
best_dt_predictions = best_dt_model.predict(X_test)
best_dt_accuracy = accuracy_score(y_test, best_dt_predictions)

print("Optimized Decision Tree Test Accuracy: ", round(best_dt_accuracy, 4))

# Optionally, you can also print the classification report for the optimized model
from sklearn.metrics import classification_report
print("\nClassification Report for Optimized Decision Tree:")
print(classification_report(y_test, best_dt_predictions, target_names=['Did Not Survive', 'Survived']))

